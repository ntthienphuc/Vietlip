"""Embed an Inno EXE and its slices in one verified Windows bootstrapper.

Uses the .NET Framework compiler already present in Windows 10/11. No external
packaging runtime is installed, downloaded or required on the receiving PC.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import struct
import subprocess
import tempfile
import zipfile
from pathlib import Path

MAGIC = b"VTLIP101"


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def package(payload: Path, output: Path, receipt: Path, csc: Path) -> dict:
    setups = list(payload.glob("VietLip-Server-Setup-*.exe"))
    if len(setups) != 1:
        raise ValueError("Expected exactly one Inno Setup EXE")
    setup = setups[0]
    slices = sorted(payload.glob(setup.stem + "-*.bin"))
    if not slices:
        raise ValueError("Expected the internal Inno payload slices")
    files = [setup, *slices]
    entries = [
        {"name": p.name, "bytes": p.stat().st_size, "sha256": sha256(p)} for p in files
    ]
    if output.exists():
        raise FileExistsError(
            "Use a new final output file; partial and older builds are not overwritten"
        )
    output.parent.mkdir(parents=True, exist_ok=True)
    receipt.parent.mkdir(parents=True, exist_ok=True)
    template = Path(__file__).with_name("InstallerBootstrap.cs")
    icon = Path(__file__).with_name("VietLip.ico")
    # TemporaryDirectory only contains files generated by this invocation.
    with tempfile.TemporaryDirectory(prefix="VietLip-package-") as name:
        work = Path(name)
        archive = work / "payload.zip"
        with zipfile.ZipFile(
            archive, "w", compression=zipfile.ZIP_STORED, allowZip64=True
        ) as bundle:
            for path in files:
                bundle.write(path, path.name)
        archive_hash = sha256(archive)
        initializers = ",\n        ".join(
            f'new PayloadFile({json.dumps(item["name"])}, {item["bytes"]}L, "{item["sha256"]}")'
            for item in entries
        )
        source = template.read_text(encoding="utf8").replace(
            "/* PAYLOAD_FILES */", initializers
        )
        source = source.replace("PAYLOAD_SHA256", archive_hash)
        code = work / "InstallerBootstrap.cs"
        code.write_text(source, encoding="utf-8-sig")
        bootstrap = work / "bootstrap.exe"
        subprocess.run(
            [
                str(csc),
                "/nologo",
                "/target:winexe",
                "/optimize+",
                "/codepage:65001",
                "/platform:x64",
                f"/out:{bootstrap}",
                f"/win32icon:{icon}",
                "/reference:System.Windows.Forms.dll",
                "/reference:System.Drawing.dll",
                "/reference:System.Core.dll",
                "/reference:System.IO.Compression.dll",
                str(code),
            ],
            check=True,
        )
        offset = bootstrap.stat().st_size
        # CreateNew protects an existing verified final release from accidental replacement.
        with (
            output.open("xb") as target,
            bootstrap.open("rb") as header,
            archive.open("rb") as data,
        ):
            shutil.copyfileobj(header, target, 1024 * 1024)
            shutil.copyfileobj(data, target, 1024 * 1024)
            target.write(
                struct.pack(
                    "<8sqq32s",
                    MAGIC,
                    offset,
                    archive.stat().st_size,
                    bytes.fromhex(archive_hash),
                )
            )
        result = {
            "format": "VietLip PE + ZIP64 + SHA256 footer",
            "output": str(output.resolve()),
            "bytes": output.stat().st_size,
            "sha256": sha256(output),
            "payload": entries,
            "payload_zip_sha256": archive_hash,
            "payload_offset": offset,
            "compiler": str(csc),
            "template_sha256": sha256(template),
        }
    receipt.write_text(json.dumps(result, indent=2), encoding="utf8")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--payload", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--receipt", required=True, type=Path)
    parser.add_argument(
        "--csc",
        type=Path,
        default=Path(r"C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe"),
    )
    args = parser.parse_args()
    result = package(args.payload, args.output, args.receipt, args.csc)
    print(
        json.dumps(
            {key: result[key] for key in ("output", "bytes", "sha256")}, indent=2
        )
    )


if __name__ == "__main__":
    main()
